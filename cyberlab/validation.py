"""Opt-in monitor-local validation of service state and actual marker ingestion."""

from __future__ import annotations

import base64
import http.client
import json
import stat
import subprocess
import time
from datetime import UTC, datetime
from urllib.parse import urlencode

from cyberlab.config import ROOT, LabConfig
from cyberlab.monitoring import MonitoringError, read_events
from cyberlab.network import SafetyError, check_isolation

MARKER = "CYBERLAB synthetic pipeline marker"
MARKER_SIDS = {1000004, 1000005, 1000006}


def is_fresh(timestamp: str, seconds: int = 600) -> bool:
    """Accept only a timestamp within the evidence window, with timezone."""
    try:
        parsed = datetime.fromisoformat(timestamp)
        return (
            parsed.tzinfo is not None
            and -5 <= (datetime.now(UTC) - parsed).total_seconds() <= seconds
        )
    except (ValueError, TypeError):
        return False


def marker_matches(record: dict, config: LabConfig, kind: str) -> bool:
    """Require fresh actual evidence from the expected lab source/destination."""
    if record.get("synthetic") or not is_fresh(record.get("timestamp")):
        return False
    if kind == "auth":
        return record.get("sender_ip") == config.hosts["target"].ip and MARKER in str(
            record.get("message", "")
        )
    if (
        record.get("src_ip") != config.hosts["kali"].ip
        or record.get("dest_ip") != config.hosts["target"].ip
    ):
        return False
    if kind == "ids":
        alert = record.get("alert")
        return (
            record.get("event_type") == "alert"
            and record.get("dest_port") == config.services["http"]
            and isinstance(alert, dict)
            and alert.get("signature_id") in MARKER_SIDS
        )
    return (
        kind == "http"
        and record.get("path") in ("/admin-test", "/security-test", "/scanner-test")
        and record.get("status") == 200
    )


def _container_running(name: str) -> bool:
    try:
        result = subprocess.run(
            ["docker", "inspect", "--format", "{{json .State}}", name],
            check=True,
            capture_output=True,
            text=True,
            timeout=4,
        )
        state = json.loads(result.stdout)
        return (
            state.get("Running") is True
            and not state.get("Restarting")
            and state.get("Health", {}).get("Status", "healthy") == "healthy"
        )
    except (OSError, subprocess.SubprocessError, ValueError, TypeError, AttributeError):
        return False


def _query_marker(config: LabConfig, query: str) -> bool:
    check_isolation(config, "monitor")
    password_file = ROOT / "local/grafana-admin-password"
    if (
        password_file.is_symlink()
        or not password_file.is_file()
        or stat.S_IMODE(password_file.stat().st_mode) & 0o077
    ):
        raise SafetyError("Grafana password file must be an ordinary private mode-600 file")
    password = password_file.read_text(encoding="utf-8")
    if not 16 <= len(password) <= 1024:
        raise SafetyError("Grafana password file has an invalid length")
    credential = base64.b64encode(f"labadmin:{password}".encode()).decode()
    now = time.time()
    parameters = urlencode(
        {
            "query": query,
            "start": int((now - 600) * 1_000_000_000),
            "end": int(now * 1_000_000_000),
            "limit": 100,
        }
    )
    connection = http.client.HTTPConnection("127.0.0.1", 3300, timeout=4)
    try:
        connection.request(
            "GET",
            f"/api/datasources/proxy/uid/cyberlab-loki/loki/api/v1/query_range?{parameters}",
            headers={"Authorization": f"Basic {credential}"},
        )
        response = connection.getresponse()
        if response.status != 200:
            return False
        data = json.loads(response.read(262_144))
        return data.get("status") == "success" and any(
            stream.get("values") for stream in data.get("data", {}).get("result", [])
        )
    except (OSError, http.client.HTTPException, ValueError, TypeError, AttributeError):
        return False
    finally:
        connection.close()


def validate_monitor(config: LabConfig, *, confirmed: bool = False) -> list[dict[str, str]]:
    """Validate fresh real lab markers; no event is generated by this function."""
    if not confirmed:
        raise SafetyError("Monitor validation requires --confirm-isolated")
    check_isolation(config, "monitor")
    results = []
    services = ["cyberlab-suricata", "rsyslog"]
    if config.mode != "lightweight":
        services.extend(("nginx", "docker"))
    for service in services:
        try:
            result = subprocess.run(
                ["systemctl", "is-active", "--quiet", service], check=False, timeout=3
            )
            active = result.returncode == 0
        except (OSError, subprocess.SubprocessError):
            active = False
        results.append({"name": service, "status": "PASS" if active else "FAIL"})
    if config.mode != "lightweight":
        for service in ("loki", "alloy", "grafana"):
            active = _container_running(f"cyberlab-monitoring-{service}-1")
            results.append({"name": f"container {service}", "status": "PASS" if active else "FAIL"})
    try:
        eve = read_events("/var/log/suricata/eve.json", config)
        auth = read_events("/var/log/cyberlab-target/auth.jsonl", config)
        access = read_events("/var/log/cyberlab-target/nginx-access.jsonl", config)
        clean = all(
            source.malformed == 0 and source.out_of_scope == 0 for source in (eve, auth, access)
        )
        stats = [
            record
            for record in eve.records
            if record.get("event_type") == "stats"
            and not record.get("synthetic")
            and is_fresh(record["timestamp"], 120)
        ]
        packets = any(
            type(record.get("stats", {}).get("capture", {}).get("kernel_packets")) is int
            and record["stats"]["capture"]["kernel_packets"] > 0
            for record in stats
        )
        alerts = any(marker_matches(record, config, "ids") for record in eve.records)
        marker = any(marker_matches(record, config, "auth") for record in auth.records)
        http_marker = any(marker_matches(record, config, "http") for record in access.records)
        for name, passed in (
            ("EVE parser and target-log scope", clean),
            ("fresh IDS packet counters", packets),
            ("fresh IDS URL marker", alerts),
            ("central auth marker", marker),
            ("central HTTP marker", http_marker),
        ):
            results.append({"name": name, "status": "PASS" if passed else "FAIL"})
    except (MonitoringError, TypeError, AttributeError):
        results.append(
            {"name": "local marker evidence (missing, stale or unreadable)", "status": "FAIL"}
        )
    if config.mode == "lightweight":
        results.append({"name": "dashboard pipeline (lightweight mode)", "status": "SKIP"})
    else:
        queries = (
            (
                "Loki auth-marker ingestion",
                '{job="target",kind="auth"} |= "CYBERLAB synthetic pipeline marker"',
            ),
            (
                "Loki IDS-marker ingestion",
                '{job="suricata",event_type="alert"} | json | alert_signature_id=~"1000004|1000005|1000006" '
                f'| src_ip="{config.hosts["kali"].ip}" | dest_ip="{config.hosts["target"].ip}" | __error__=""',
            ),
            (
                "Loki HTTP-marker ingestion",
                '{job="target",kind="nginx_access"} | json '
                f'| src_ip="{config.hosts["kali"].ip}" | dest_ip="{config.hosts["target"].ip}" '
                '| path=~"/admin-test|/security-test|/scanner-test" | status=200 | __error__=""',
            ),
        )
        for name, query in queries:
            try:
                passed = _query_marker(config, query)
            except (SafetyError, OSError):
                passed = False
            results.append({"name": name, "status": "PASS" if passed else "FAIL"})
    return results
